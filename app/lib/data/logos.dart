LogoSpec? logoFor(String? idOrName) {
  if (idOrName == null || idOrName.isEmpty) return null;
  final key = idOrName.trim().toLowerCase().replaceAll(' ', '-').replaceAll('_', '-');
  final direct = kLogoRegistry[key];
  if (direct != null) return direct;
  final compact = key.replaceAll('-', '');
  for (final e in kLogoRegistry.entries) {
    if (e.key.replaceAll('-', '') == compact) return e.value;
  }
  return kLogoRegistry[key.split('-').first];
}
